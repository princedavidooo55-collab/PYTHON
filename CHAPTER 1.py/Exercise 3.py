# What is the difference between a compiler and an interpreter?
# ans: An interpreter reads the source code of the program as written by the programmer,parses the source code, 
# and interprets the instructions on the fly 
# while A compiler needs to be handed the entire program in a file,
# and then it runs a process to translate the high-level source code into machine language
#  and then the compiler puts the resulting machine language into a file for later execution.